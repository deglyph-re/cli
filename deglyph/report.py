# deglyph
"""
Markdown and single-file HTML report renderers for `deglyph scan` output.

`scan.to_text` is for terminals and `scan.to_sarif` is for code-scanning
ingestion. This module covers the in-between: a markdown report shaped for a
GitHub PR comment, and a self-contained HTML report you can drop on a static
host or attach to a CI run.

Both take the same `[(path, findings)]` shape `scan` returns and group by
severity, then by rule. A clean run renders a "no findings" body so the PR
comment is still useful (and idempotent for sticky-comment updates).

Public: to_markdown, to_html.
"""

from __future__ import annotations

import html
from collections import defaultdict

from . import __version__
from .scan import CATEGORY_LABEL, CATEGORY_ORDER, Finding

_LEVEL_ORDER = ("error", "warning", "note")
_LEVEL_LABELS = {"error": "Errors", "warning": "Warnings", "note": "Notes"}


def _by_level(findings: list[Finding]) -> dict[str, list[Finding]]:
    grouped: dict[str, list[Finding]] = defaultdict(list)
    for f in findings:
        grouped[f.level].append(f)
    return grouped


def _by_category(findings: list[Finding]) -> dict[str, list[Finding]]:
    grouped: dict[str, list[Finding]] = defaultdict(list)
    for f in findings:
        grouped[f.category].append(f)
    return grouped


def _totals(results: list[tuple[str, list[Finding]]]) -> dict[str, int]:
    out: dict[str, int] = {"error": 0, "warning": 0, "note": 0}
    for _p, findings in results:
        for f in findings:
            out[f.level] = out.get(f.level, 0) + 1
    return out


def _summary_line(totals: dict[str, int]) -> str:
    e, w, n = totals.get("error", 0), totals.get("warning", 0), totals.get("note", 0)
    if e == w == n == 0:
        return "0 findings (clean)"
    return f"{e} error(s), {w} warning(s), {n} note(s)"


def to_markdown(
    results: list[tuple[str, list[Finding]]],
    *,
    title: str = "deglyph scan",
) -> str:
    """Render a scan result list as a markdown report suitable for a PR comment."""
    totals = _totals(results)
    lines: list[str] = []
    lines.append(f"## {title}: {_summary_line(totals)}")
    lines.append("")

    if not results:
        lines.append("_No files scanned._")
        return "\n".join(lines) + _footer_md()

    if all(not findings for _p, findings in results):
        lines.append("Clean across all scanned files.")
        return "\n".join(lines) + _footer_md()

    for path, findings in results:
        lines.append(f"### `{path}`")
        if not findings:
            lines.append("_No findings._")
            lines.append("")
            continue
        by_cat = _by_category(findings)
        for cat in CATEGORY_ORDER:
            group = by_cat.get(cat) or []
            if not group:
                continue
            lines.append(f"#### {CATEGORY_LABEL[cat]} ({len(group)})")
            grouped = _by_level(group)
            for level in _LEVEL_ORDER:
                items = grouped.get(level) or []
                if not items:
                    continue
                lines.append(f"**{_LEVEL_LABELS[level]}** ({len(items)})")
                for f in items:
                    lines.append(f"- `{f.rule}` at `{f.where}`: {f.message}")
                lines.append("")

    return "\n".join(lines) + _footer_md()


def _footer_md() -> str:
    return (
        f"\n---\nGenerated by [deglyph](https://deglyph.dev) {__version__}. "
        f"Findings are heuristics; confirm before remediating."
    )


