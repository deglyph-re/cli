def to_html(
    results: list[tuple[str, list[Finding]]],
    *,
    title: str = "deglyph scan",
) -> str:
    """Render a self-contained HTML report (one file, no external assets)."""
    totals = _totals(results)
    body: list[str] = []
    body.append(f"<h1>{html.escape(title)}</h1>")

    if any(totals.values()):
        body.append('<div class="summary">')
        for level in _LEVEL_ORDER:
            count = totals.get(level, 0)
            if count:
                body.append(
                    f'<span class="pill {level}">{count} {_LEVEL_LABELS[level].lower()}</span>'
                )
        body.append("</div>")
    else:
        body.append('<div class="summary"><span class="pill clean">clean</span></div>')

    if not results:
        body.append("<p><em>No files scanned.</em></p>")
    else:
        for path, findings in results:
            body.append(f"<h2><code>{html.escape(path)}</code></h2>")
            if not findings:
                body.append("<p><em>No findings.</em></p>")
                continue
            by_cat = _by_category(findings)
            for cat in CATEGORY_ORDER:
                group = by_cat.get(cat) or []
                if not group:
                    continue
                body.append(f"<h3>{CATEGORY_LABEL[cat]} ({len(group)})</h3>")
                grouped = _by_level(group)
                for level in _LEVEL_ORDER:
                    items = grouped.get(level) or []
                    if not items:
                        continue
                    body.append(f"<h4>{_LEVEL_LABELS[level]} ({len(items)})</h4>")
                    body.append("<table>")
                    body.append(
                        "<tr><th>rule</th><th>location</th><th>message</th></tr>"
                    )
                    for f in items:
                        body.append(
                            "<tr>"
                            f'<td><code class="rule-{level}">'
                            f"{html.escape(f.rule)}</code></td>"
                            f"<td><code>{html.escape(f.where)}</code></td>"
                            f"<td>{html.escape(f.message)}</td>"
                            "</tr>"
                        )
                    body.append("</table>")

    body.append(
        '<footer>Generated by <a href="https://deglyph.dev">deglyph</a> '
        f"{html.escape(__version__)}. Findings are heuristics; confirm before remediating.</footer>"
    )

    return (
        "<!doctype html>\n"
        '<html lang="en"><head>'
        '<meta charset="utf-8">'
        f"<title>{html.escape(title)}</title>"
        f"<style>{_HTML_STYLE}</style>"
        "</head><body>" + "\n".join(body) + "</body></html>\n"
    )


__all__ = ["to_markdown", "to_html"]
